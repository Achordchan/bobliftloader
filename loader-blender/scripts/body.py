    hood=g.empty('机罩斜面坐标架',(0,1.36,.43));hood.rotation_euler.x=math.pi/3
    # Centre and side panels share boundaries; their front faces must never overlap.
    for s in [-1,1]:
        verts=[(s*.35,0,.018),(s*.335,1.15,.018),(s*.195,1.15,.018),(s*.192,1.01,.018),(s*.155,.45,.018),(s*.18,0,.018)]
        plate=g.mesh('机罩上面折板',verts,[tuple(range(6))],'paint',hood)
        solid=plate.modifiers.new('钢板厚度','SOLIDIFY');solid.thickness=.012
        bevel=plate.modifiers.new('折边圆角','BEVEL');bevel.width=.004;bevel.segments=3
        plate=g.mesh('机罩外侧折边',[(s*.35,0,.018),(s*.335,1.15,.018),(s*.422,1.15,-.10),(s*.45,0,-.12)],[(0,1,2,3)],'paint',hood)
        mod=plate.modifiers.new('钣金厚度','SOLIDIFY');mod.thickness=.012
        g.hose('机罩密封边',[(s*.45,0,-.12),(s*.432,.65,-.11),(s*.422,1.15,-.10)],.011,'rubber',hood)
        g.mesh('凹槽侧壁',[(s*.155,.45,.018),(s*.192,1.01,.018),(s*.157,.98,-.103),(s*.123,.49,-.103)],[(0,1,2,3)],'paint',hood)
    g.mesh('机罩下端面',[(-.18,0,.018),(.18,0,.018),(.155,.45,.018),(-.155,.45,.018)],[(0,1,2,3)],'paint',hood)
    g.mesh('机罩上端面',[(-.192,1.01,.018),(.192,1.01,.018),(.195,1.15,.018),(-.195,1.15,.018)],[(0,1,2,3)],'paint',hood)
    g.mesh('凹槽底部折面',[(-.155,.45,.018),(.155,.45,.018),(.123,.49,-.103),(-.123,.49,-.103)],[(0,1,2,3)],'paint',hood)
    g.mesh('凹槽后壁',[(-.192,1.01,.018),(-.157,.98,-.103),(.157,.98,-.103),(.192,1.01,.018)],[(0,1,2,3)],'paint',hood)
