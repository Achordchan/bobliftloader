    g.box('后部发动机罩',.75,.67,.19,0,1.20,-1.09,'dark',bevel=.055)
    for i in range(9):g.box('后部散热百叶',.54,.018,.015,0,.94+i*.052,-1.192,'black',bevel=.004)
    g.box('操作员站立踏板',.78,.063,.38,0,.46,-1.25,'dark')
    for i in range(12):
        for j in range(4):g.box('踏板防滑凸点',.03,.009,.026,-.33+i*.060,.498,-1.38+j*.072,'steel',bevel=.002)
    g.rod('踏板外沿',(-.37,.49,-1.43),(.37,.49,-1.43),.012,'steel')
    for s in [-1,1]:g.box('后反光片',.11,.057,.018,s*.29,.66,-1.20,'red',bevel=.008)
