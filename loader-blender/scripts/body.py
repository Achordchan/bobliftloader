    vent=g.empty('通风格栅安装架',(0,.855,-.047),hood);vent.rotation_euler.x=-.80
    grille=g.box('真实镂空蜂窝格栅',.38,.16,.009,0,0,0,'paint',vent,bevel=.001)
    holes=[]
    for row in range(5):
        for col in range(12):
            x=-.154+col*.028+(row%2)*.014;y=-.048+row*.025
            if x<=.16:holes.append(((x,y,0),.0115,.06))
    g.boolean_holes(grille,holes,'z',6)
    g.box('格栅后部暗腔',.365,.15,.014,0,0,-.045,'black',vent)
    g.box('格栅上沿',.394,.018,.075,0,.079,-.018,'paint',vent)
    lamp=g.empty('六灯珠工作灯',(0,1.075,.058),hood);lamp.rotation_euler.x=-.90
    g.box('工作灯橙色罩',.365,.123,.075,0,0,-.02,'paint',lamp,bevel=.015)
    g.box('工作灯密封框',.318,.089,.043,0,0,.024,'rubber',lamp,bevel=.013)
    g.box('灯珠黑色底板',.269,.059,.010,0,0,.05,'black',lamp)
    for i in range(6):
        x=-.108+i*.043
        g.rod('反射杯',(x,0,.053),(x,0,.066),.016,'reflector',lamp,r2=.019,bevel=.001)
        g.ring('反射杯镜面边',(x,0,.067),.019,.002,'chrome',lamp,'z')
        g.rod('LED发光芯片',(x,0,.069),(x,0,.074),.006,'amber',lamp,bevel=.001)
    g.box('透明玻璃罩',.275,.064,.008,0,0,.080,'lens',lamp,bevel=.003)
    for s in [-1,1]:g.rod('灯框安装螺钉',(s*.147,0,.045),(s*.147,0,.060),.006,'steel',lamp,vertices=6)
    for s in [-1,1]:
        g.profile('侧面机架护板',[(-1.01,.49),(-1.07,1.40),(-.85,1.72),(-.59,1.60),(-.24,1.10),(-.40,.96),(-.49,.54)],.042,s*.48,'dark',bevel=.008)
        g.profile('后部防护折边',[(-.99,.48),(-1.10,.79),(-1.13,1.44),(-.95,1.66),(-.86,1.49),(-.90,.72)],.026,s*.43,'black',bevel=.012)
        for z,y in [(-.98,.62),(-1.01,1.15),(-.79,1.49),(-.60,1.26),(-.55,.72),(-.88,1.57)]:g.bolt('侧护板紧固件',s*.507,y,z,radius=.018,side=s)
        g.box('侧面反光片',.018,.18,.055,s*.515,1.04,-.94,'amber',bevel=.007)
        g.profile('检修盖快开锁',[(-.71,.60),(-.70,.70),(-.68,.735),(-.65,.70),(-.65,.60)],.007,s*.517,'steel',bevel=.004)
