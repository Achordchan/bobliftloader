// Build the BL-T360-H / BL-T460-H showcase for the WordPress theme (bobliftloader.com/bl-t360-t460/), from this folder.
//
// The page is written in Chinese and swapped into other languages in the browser (i18n/). The main site is English, so
// the theme copy is English in the HTML itself: the page is opened here in English in a headless browser (page scripts
// blocked, only the translation runs) and the translated markup is saved. Scripts still translate what they write later,
// so i18n.js ships too, fixed to English and with the Chinese → English rows only; the language menu is removed.
//
// The theme puts the site header above the page's own chapter bar and adds its styles (assets/css/showcase.css).
// The theme serves the page at /bl-t360-t460/ and its files from wp-content/themes/…/assets/bl360/, so every relative
// asset address is prefixed with the theme folder: {{BASE}} in the saved markup (templates/bl360.php fills it in) and
// window.BL360_BASE in the scripts. The three real-machine clips are the theme's own copies (assets/videos/, also on the
// product pages), not a second set. The specification table and the contact section are written by the theme from the
// product records, so the page always matches the product pages.
//
// Usage: node loader-experience/scripts/build_wp.mjs   (writes assets/bl360/ and templates/bl360/ in the theme)
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn, spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const THEME = join(ROOT, '..');
const OUT = join(THEME, 'assets', 'bl360');
const TPL = join(THEME, 'templates', 'bl360');
// Not part of the page: sources, notes, the old pre-rendered clips (motion), the unused 24-frame orbit and its loader,
// and the real-machine clips the theme already has in assets/videos/.
const SKIP = new Set(['design', 'scripts', 'tests', 'README.md', '.DS_Store', '__pycache__', 'edgeone.json', 'index.html',
  'favicon.ico', 'favicon.svg', 'favicon-32.png', 'apple-touch-icon.png', 'sequence.js']);
const SKIP_ASSETS = new Set(['motion', 'orbit', 'real-motion']);

const fail = message => { console.error(message); process.exit(1); };
const replaceOnce = (text, from, to, where) => { if (!text.includes(from)) fail(`${where}: "${from}" not found`); return text.replace(from, to); };

for (const f of ['assets/model/loader.glb', 'assets/env/sky.hdr']) {
  const src = join(ROOT, f), gz = src + '.gz';
  if (!existsSync(gz) || !gunzipSync(readFileSync(gz)).equals(readFileSync(src))) fail(`${f}.gz is missing or out of date: run gzip -9kfn ${f}`);
}
for (const name of ['bucket', 'drive', 'lift']) if (!existsSync(join(THEME, 'assets', 'videos', name + '.mp4'))) fail(`assets/videos/${name}.mp4 is missing in the theme`);

/** The site names the models BL-T360-H / BL-T460-H; the page's own wordmark keeps the short form. */
const siteNames = text => text.replace(/BL-T([34]60)(?![-\w])/g, 'BL-T$1-H');

/** Asset addresses in scripts: 'assets/…' and `assets/…` start from the theme folder. */
const prefixScript = code => code
  .replace(/`url\(assets\//g, '`url(${window.BL360_BASE}assets/')
  .replace(/`assets\//g, '`${window.BL360_BASE}assets/')
  .replace(/'assets\//g, "window.BL360_BASE+'assets/");

// 1 · Files. Scripts and styles go through esbuild from a staging copy (scripts with their asset addresses prefixed).
rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT, { recursive: true });
const stage = mkdtempSync(join(tmpdir(), 'bl360-'));
const minify = [];
(function walk(dir) {
  for (const name of readdirSync(join(ROOT, dir))) {
    if (SKIP.has(name) || name.startsWith('.') || (dir === 'assets' && SKIP_ASSETS.has(name))) continue;
    const rel = join(dir, name), st = statSync(join(ROOT, rel));
    if (st.isDirectory()) { walk(rel); continue; }
    if (/\.(js|css)$/.test(name) && !/\.min\.js$/.test(name)) {
      let text = readFileSync(join(ROOT, rel), 'utf8');
      if (name.endsWith('.js') && !rel.startsWith('assets')) text = prefixScript(text);
      if (rel === 'app.js') text = replaceOnce(text, '`${window.BL360_BASE}assets/real-motion/${name}.mp4`', '`${window.BL360_VIDEOS}${name}.mp4`', rel);
      if (rel === join('i18n', 'i18n.js')) text = replaceOnce(text, 'const lang = pick();', "const lang = 'en'; // the theme copy: English only, as the site", rel);
      if (rel === join('i18n', 'strings.js')) {
        const rows = (new Function('window', text + '; return window.BOBLIFT_I18N_ROWS;'))({});
        text = '// Chinese → English rows for the scripts (generated by scripts/build_wp.mjs from i18n/strings.js).\nwindow.BOBLIFT_I18N_ROWS = ' + JSON.stringify(rows.map(r => [r[0], siteNames(r[1])])) + ';\n';
      }
      mkdirSync(join(stage, dir), { recursive: true }); writeFileSync(join(stage, rel), text);
      minify.push(rel);
    } else { mkdirSync(join(OUT, dir), { recursive: true }); cpSync(join(ROOT, rel), join(OUT, rel)); }
  }
})('');
const run = spawnSync('npx', ['--yes', 'esbuild@0.25', ...minify, '--minify', '--charset=utf8', '--log-level=warning', `--outdir=${OUT}`, `--outbase=${stage}`], { cwd: stage, stdio: 'inherit' });
if (run.status !== 0) process.exit(run.status ?? 1);

// 2 · Markup, in English: the page opened with only its translation running.
const html = readFileSync(join(ROOT, 'index.html'), 'utf8');
const port = 4300 + Math.floor(Math.random() * 500);
const server = spawn('python3', ['-m', 'http.server', String(port), '--bind', '127.0.0.1'], { cwd: ROOT, stdio: 'ignore' });
let body;
try {
  const { chromium } = createRequire(import.meta.url)('playwright');
  await new Promise(r => setTimeout(r, 800));
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.route('**/*', route => /\/i18n\/|index\.html|\/$|\?lang=/.test(route.request().url()) ? route.continue() : route.abort());
  await page.goto(`http://127.0.0.1:${port}/index.html?lang=en#specs`, { waitUntil: 'load' });
  body = await page.evaluate(() => {
    document.getElementById('lang')?.remove(); // the site has one language; the page follows it
    return document.body.outerHTML;
  });
  await browser.close();
} finally { server.kill(); }
if (/[一-鿿]/.test(body.replace(/<script>[\s\S]*?<\/script>/g, ''))) {
  const left = [...new Set(body.replace(/<script>[\s\S]*?<\/script>/g, '').match(/[^<>"]*[一-鿿][^<>"]*/g))].slice(0, 10);
  fail('Chinese left in the English markup (add rows to i18n/strings.js):\n' + left.join('\n'));
}
const prefixMarkup = text => text.replace(/(["\s,(])assets\//g, '$1{{BASE}}assets/');
// The theme writes these two sections from the product records and the company settings.
const cut = (text, re, mark) => { if (!re.test(text)) fail(`section for ${mark} not found`); return text.replace(re, mark); };
body = cut(body, /<section class="exp-specs"[\s\S]*?<\/section>/, '{{SPECS}}');
body = cut(body, /<section class="exp-contact"[\s\S]*?<\/section>/, '{{CONTACT}}');
const wordmark = body.match(/<h2 id="finale-title">[^<]*<\/h2>/)?.[0];
if (!wordmark) fail('finale wordmark not found');
body = siteNames(body).replace(siteNames(wordmark), wordmark);
// The closing comparison line is written by the theme from the product records too.
body = cut(body, /(<div class="exp-finale-bottom"><div><h3>[^<]*<\/h3>)<p>[^<]*<\/p>/, '$1<p>{{COMPARE}}</p>');
body = prefixMarkup(body).replace(/^<body[^>]*>/, '').replace(/<\/body>$/, '');

// Head: the opening script and the page's styles and scripts (the theme adds the title, SEO tags and tracking).
const head = html.slice(html.indexOf('<link rel="preload"'), html.indexOf('</head>'));
let headOut = prefixScript(head)
  .replace(/<script type="importmap">[\s\S]*?<\/script>/, '{{IMPORTMAP}}')
  .replace(/(href|src)="(?!https?:|\/|\{\{)([^"]+)"/g, '$1="{{BASE}}$2"');
headOut = replaceOnce(headOut, "'正在载入三维模型 ' + n + '%'", "'Loading 3D model ' + n + '%'", 'index.html head');
mkdirSync(TPL, { recursive: true });
writeFileSync(join(TPL, 'head.html'), headOut.trim() + '\n');
writeFileSync(join(TPL, 'body.html'), body.trim() + '\n');
writeFileSync(join(TPL, 'importmap.json'), JSON.stringify(JSON.parse(html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports));
rmSync(stage, { recursive: true, force: true });

let files = 0, bytes = 0;
(function count(dir) { for (const n of readdirSync(dir)) { const p = join(dir, n), st = statSync(p); if (st.isDirectory()) count(p); else { files++; bytes += st.size; } } })(OUT);
console.log(`${relative(process.cwd(), OUT)}: ${files} files, ${(bytes / 1e6).toFixed(1)} MB (${minify.length} minified); ${relative(process.cwd(), TPL)}: head, body, import map`);
