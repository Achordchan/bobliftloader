<?php
/** Exercise the settings compatibility bridge at REST dispatch and option-store boundaries, without a database. */
declare(strict_types=1);
require __DIR__ . '/fixtures/wp-memory.php';
require __DIR__ . '/../inc/bootstrap.php';
require __DIR__ . '/../inc/wp-admin.php';
require __DIR__ . '/../inc/wp-content-editor.php';
require __DIR__ . '/../inc/wp-support.php';
$checks = 0;
$check = static function (bool $ok, string $message) use (&$checks): void { $checks++; if (!$ok) throw new RuntimeException($message); };
run_hook('rest_api_init');
$setting = $GLOBALS['settings']['bl_catalogue_url'];
$check($setting['show_in_rest'] === true && $setting['type'] === 'string' && $setting['default'] === '', 'legacy REST setting schema missing');
$check($setting['sanitize_callback']('https://example.test/catalogue.pdf') === esc_url_raw('https://example.test/catalogue.pdf', ['http', 'https']), 'setting sanitizer changed');
$read = static fn() => run_filter('rest_pre_get_setting', null, 'bl_catalogue_url');
$check($read() === '', 'default setting must expose configured URL, not bundled asset URL');
$GLOBALS['options']['bl_catalogue_url'] = 'https://example.test/legacy.pdf';
$check($read() === 'https://example.test/legacy.pdf', 'legacy setting not inherited');
$primary = bl_downloads_catalogue_row();
$manual = array_replace($primary, ['id' => 'manual', 'title' => 'Manual', 'type' => 'manual']);
$GLOBALS['options']['bl_downloads'] = ['items' => [$manual, $primary]];
$handler = ['callback' => static function (WP_REST_Request $request) use ($read, $check): array {
    $check(!array_key_exists('bl_catalogue_url', $request->get_params()), 'core would write legacy option');
    return ['bl_catalogue_url' => $read(), 'other_params' => $request->get_params()];
}];
$dispatch = static fn(WP_REST_Request $request) => run_filter('rest_dispatch_request', null, $request, '/wp/v2/settings', $handler);
$GLOBALS['caps'] = ['manage_options' => true, 'edit_pages' => false];
$before = $GLOBALS['options'];
$request = new WP_REST_Request(['bl_catalogue_url' => 'https://example.test/产品画册.zip', 'title' => 'Site title']);
$result = $dispatch($request);
$check($result['bl_catalogue_url'] === $request->get_param('bl_catalogue_url'), 'setting write/read mismatch');
$check($result['other_params'] === ['title' => 'Site title'], 'other settings lost');
$check($request->get_param('bl_catalogue_url') === $result['bl_catalogue_url'], 'dispatch mutated original request');
$check(bl_downloads_saved()['items'][0] === $manual && bl_downloads_saved()['items'][1]['url'] === $result['bl_catalogue_url'], 'bridge overwrote another row or used display order');
$check(array_diff_key($GLOBALS['options'], ['bl_downloads' => true]) === array_diff_key($before, ['bl_downloads' => true]), 'bridge wrote another option');
$check(bl_content_history('downloads')[0]['content'] === $before['bl_downloads'], 'bridge bypassed unified history');
$check(bl_catalogue_rest_read()['bl_catalogue_url'] === $read(), 'REST interfaces disagree');
$check(run_filter('rest_pre_get_setting', 'untouched', 'title') === 'untouched', 'unrelated settings read intercepted');
$state = $GLOBALS['options'];
$GLOBALS['fail_option'] = 'bl_downloads';
$check(is_wp_error($dispatch(new WP_REST_Request(['bl_catalogue_url' => 'https://example.test/failure.pdf']))) && $GLOBALS['options'] === $state, 'failed writer reported success or partially persisted');
unset($GLOBALS['fail_option']);
$GLOBALS['caps'] = ['manage_options' => false, 'edit_pages' => true];
$check(is_wp_error($dispatch(new WP_REST_Request(['bl_catalogue_url' => '']))) && $GLOBALS['options'] === $state, 'settings bridge granted editor admin permissions');
$GLOBALS['caps']['manage_options'] = true;
$check($dispatch(new WP_REST_Request(['bl_catalogue_url' => null]))['bl_catalogue_url'] === '', 'null did not reset configured URL');
$check($GLOBALS['options']['bl_catalogue_url'] === $before['bl_catalogue_url'], 'reset touched legacy option');
$state = $GLOBALS['options'];
$check($dispatch(new WP_REST_Request(['title' => 'Only title'])) === null && $GLOBALS['options'] === $state, 'unrelated update intercepted');
$check(run_filter('rest_dispatch_request', 'handled', $request, '/wp/v2/settings', $handler) === 'handled', 'prior dispatch result ignored');
$check(run_filter('rest_dispatch_request', null, $request, '/boblift/v1/catalogue', $handler) === null, 'unrelated route intercepted');
echo "Catalogue settings: $checks checks passed\n";
